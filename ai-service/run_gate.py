#!/usr/bin/env python3
"""TeachMeWrite AI golden-set gate. Runs each case 3 times, 2-of-3 rule.
Usage: python run_gate.py <service_url> [--runs N] [--threshold K] [--judge] [--out result.json]
Exit 0 = all cases pass, exit 1 = any case fails. This is what CI reads."""
import argparse, json, os, sys, time
from pathlib import Path
import httpx

def _norm(resp):
    if hasattr(resp, "model_dump"):
        return resp.model_dump()
    return resp

JUDGE_PROMPT = """You are a Senior English Teacher and AI Evaluator for the Pakistani education system.
You will be given a STUDENT TEXT and the AI FEEDBACK generated by an automated system.

Grade the AI FEEDBACK on three criteria using a scale of 1 to 5:
1. ACCURACY: Did the AI correctly identify the actual grammar/clarity errors?
2. HELPFULNESS: Is the explanation actionable for a Pakistani student?
3. TONE: Is the feedback professional, respectful, and encouraging?

Return ONLY a JSON object (no markdown, no extra text):
{{
  "accuracy_score": int,
  "helpfulness_score": int,
  "tone_score": int,
  "reasoning": "1-2 sentences"
}}

STUDENT TEXT:
{student_text}

AI FEEDBACK:
{ai_feedback}
"""

def judge_feedback(student_text, ai_feedback, client):
    """Call the LLM judge. Returns dict with scores. Raises on failure."""
    formatted = JUDGE_PROMPT.format(
        student_text=student_text,
        ai_feedback=json.dumps(ai_feedback, indent=2)
    )
    resp = client.messages.create(
        model="claude-haiku-4-5-20251001",
        max_tokens=500,
        system="You are a strict English teacher evaluator. Respond only with valid JSON.",
        messages=[{"role": "user", "content": formatted}]
    )
    raw = resp.content[0].text.strip()
    raw = raw.removeprefix("```json").removeprefix("```").removesuffix("```").strip()
    return json.loads(raw)

def score_case(case, response, judge_client=None, min_helpfulness=3):
    resp = _norm(response)
    exp = case["expected"]
    failures = []
    issues = resp.get("issues", [])
    cats = {i["category"] for i in issues}
    blob = " ".join((i.get("explanation","")+" "+i.get("example","")).lower() for i in issues)
    for c in exp["must_flag_categories"]:
        if c not in cats: failures.append(f"missing category '{c}'")
    for c in exp["must_not_flag_categories"]:
        if c in cats: failures.append(f"forbidden category '{c}' flagged")
    lo, hi = exp["score_range"]
    score = resp.get("overall_score")
    if score is None: failures.append("missing overall_score")
    elif not (lo <= score <= hi): failures.append(f"score {score} outside [{lo},{hi}]")
    needles = exp["must_mention_any"]
    if needles and not any(n.lower() in blob for n in needles):
        failures.append(f"none of {needles} appeared")
    
    # NEW: Judge gate
    if judge_client is not None:
        try:
            judge_eval = judge_feedback(case["student_text"], resp, judge_client)
            help_score = judge_eval.get("helpfulness_score", 0)
            if help_score < min_helpfulness:
                failures.append(f"judge helpfulness {help_score} < {min_helpfulness}: {judge_eval.get('reasoning','')}")
        except Exception as e:
            failures.append(f"judge exception: {e}")
    
    return {"pass": len(failures)==0, "failures": failures}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("service_url")
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--threshold", type=int, default=2)
    ap.add_argument("--golden", default=str(Path(__file__).parent / "golden_set.jsonl"))
    ap.add_argument("--out", default="gate_result.json")
    ap.add_argument("--judge", action="store_true", help="Enable LLM-as-a-Judge quality gate")
    ap.add_argument("--min-helpfulness", type=int, default=3)
    args = ap.parse_args()

    # Optional judge setup
    judge_client = None
    if args.judge:
        from anthropic import Anthropic
        if not os.environ.get("ANTHROPIC_API_KEY"):
            print("ERROR: --judge requires ANTHROPIC_API_KEY", file=sys.stderr); sys.exit(1)
        judge_client = Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"])
        print(f"Judge enabled (min helpfulness: {args.min_helpfulness})")

    cases = [json.loads(l) for l in Path(args.golden).read_text(encoding="utf-8").splitlines() if l.strip()]
    if not cases: print("ERROR: empty golden set", file=sys.stderr); sys.exit(1)

    try:
        h = httpx.get(f"{args.service_url}/health", timeout=30.0)
        if h.status_code != 200: print(f"ERROR: /health {h.status_code}", file=sys.stderr); sys.exit(1)
    except Exception as e:
        print(f"ERROR: service unreachable: {e}", file=sys.stderr); sys.exit(1)

    results, t0 = [], time.time()
    for i, case in enumerate(cases, 1):
        payload = {"student_text": case["student_text"], "level": case["level"]}
        runs = []
        for _ in range(args.runs):
            try:
                r = httpx.post(f"{args.service_url}/feedback", json=payload, timeout=120.0)
                runs.append(score_case(case, r.json(), judge_client, args.min_helpfulness)
                            if r.status_code == 200
                            else {"pass": False, "failures": [f"HTTP {r.status_code}"]})
            except Exception as e:
                runs.append({"pass": False, "failures": [f"exception: {e}"]})
        pc = sum(1 for x in runs if x["pass"])
        verdict = "PASS" if pc >= args.threshold else "FAIL"
        results.append({"id": case["id"], "verdict": verdict, "pass_count": pc, "runs": runs})
        print(f"[{i:02d}/{len(cases)}] {case['id']}  {verdict} {pc}/{args.runs}")
        if verdict == "FAIL":
            for x in runs:
                if not x["pass"]:
                    for f in x["failures"]: print(f"           - {f}")
                    break

    passed = sum(1 for r in results if r["verdict"] == "PASS")
    print(f"\nGate: {passed}/{len(results)} passed in {time.time()-t0:.1f}s")
    Path(args.out).write_text(json.dumps({"service_url": args.service_url, "passed": passed,
        "total": len(results), "runs": args.runs, "threshold": args.threshold,
        "judge_enabled": args.judge, "judge_min_helpfulness": args.min_helpfulness,
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "detailed": results}, indent=2))
    sys.exit(0 if passed == len(results) else 1)

if __name__ == "__main__":
    main()
